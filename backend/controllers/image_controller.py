_MAX_FETCH_TIMEOUT_SECONDS = 3600  # absolute maximum: 60 minutes
_STALE_HEARTBEAT_MINUTES   = 20    # if no progress.json heartbeat for this long, mark stale


def _fetch_timeout_seconds(nx: int) -> int:
    """
    Return a tile-count-aware hard timeout for the acquisition worker.

    1x1  -> 15 min
    2x2  -> 30 min
    3x3  -> 45 min
    >=4  -> 60 min (capped)
    """
    clamped_nx = max(1, int(nx))
    timeout_minutes = min(60, 15 + 15 * (clamped_nx - 1))
    return timeout_minutes * 60


def _mark_pair_error(pair_id: str, message: str) -> None:
    """
    Mark an active acquisition as ``error`` without overwriting a
    terminal state such as ``done``.

    The transition is intentionally conditional:
        pending  -> error    allowed
        fetching -> error    allowed
        done     -> error    forbidden
        error    -> error    forbidden

    This prevents the outer timeout/error handler from racing with the inner
    acquisition worker and changing a successfully completed pair from
    ``done`` back to ``error``.

    A fresh, independent DB session is used so that an expired/dirty worker
    session cannot prevent the terminal error state from being persisted.
    The error progress artifact is written only when the database transition
    actually succeeds.
    """
    error_message = str(message)[:1000]
    db2 = SessionLocal()
    try:
        rows_updated = db2.query(AOIImagePair).filter(
            AOIImagePair.id == pair_id,
            AOIImagePair.status.in_(("pending", "fetching")),
        ).update(
            {
                "status": "error",
                "error_message": error_message,
            },
            synchronize_session=False,
        )

        if rows_updated != 1:
            db2.rollback()
            return

        db2.commit()

    except Exception:
        db2.rollback()
        return

    finally:
        db2.close()

    _write_progress(pair_id, error_message, state="error")



def _do_fetch(
    pair_id: str,
    lat: float,
    lon: float,
    before_date: str,
    after_date: str,
    cover_area: str,
    aoi_payload: dict[str, Any] | None = None,
) -> None:
    """
    Execute the Earth Engine acquisition and update the image-pair record.

    Notes:
    - GEE research mode is authoritative.
    - before_date / after_date are retained as legacy display values.
    - The full AOI payload is passed when available so polygon/rectangle AOIs
      are handled correctly.
    - A tile-count-aware wall-clock timeout is enforced (15–60 min).
    - A shared timeout_event is used so the progress writer exits cleanly
      if the timeout fires before the worker finishes.
    """
    import threading as _threading

    # Parse tile count from cover_area to compute adaptive timeout
    try:
        nx = int(str(cover_area).rstrip("x"))
    except (ValueError, TypeError):
        nx = 1
    timeout_secs = _fetch_timeout_seconds(nx)

    # timeout_event: set by the outer thread when the timeout fires,
    # read by the progress callback so it skips writes after expiry.
    timeout_event = _threading.Event()

    # Shared result container for the inner worker thread.
    _result: dict[str, Any] = {}

    def _run_acquisition() -> None:
        db = SessionLocal()
        try:
            pair = db.get(AOIImagePair, pair_id)
            if not pair:
                _result["error"] = "Image pair record not found"
                return

            # Atomically claim the pair:
            # pending -> fetching
            #
            # If another thread already moved the pair to error/done,
            # do not resurrect it back to fetching.
            rows_claimed = db.query(AOIImagePair).filter(
                AOIImagePair.id == pair_id,
                AOIImagePair.status == "pending",
            ).update(
                {
                    "status": "fetching",
                    "error_message": None,
                },
                synchronize_session=False,
            )

            if rows_claimed != 1:
                db.rollback()
                _result["error"] = (
                    "Image pair is no longer pending; "
                    "acquisition worker was not allowed to claim it."
                )
                return

            db.commit()

            def update_progress(message: str) -> None:
                # Do not write progress after the timeout has fired.
                if timeout_event.is_set():
                    return
                _write_progress(pair_id, message, state="fetching")

            update_progress("Initializing acquisition...")

            # Lazy import — keep inside try so ImportError is caught and
            # correctly transitions the pair to 'error' instead of silently
            # leaving it in 'fetching'.
            from services.gee_service import fetch_image_pair

            update_progress("Checking Sentinel-2 / Sentinel-1 coverage...")

            result = fetch_image_pair(
                lat=lat,
                lon=lon,
                before_date=before_date,
                after_date=after_date,
                cover_area=cover_area,
                pair_id=pair_id,
                update_progress=update_progress,
                aoi=aoi_payload,
                temporal_mode="research",
                model_id="geonexus_p4b_k30",
            )

            # Write acquisition metadata for the API / UI.
            acquisition_metadata = {
                "pair_id":       pair_id,
                "run_id":        result.get("run_id"),
                "model_id":      "geonexus_p4b_k30",
                "t1_window":     result.get("t1_window"),
                "t2_window":     result.get("t2_window"),
                "crs":           result.get("crs"),
                "nx":            result.get("nx"),
                "patch_px":      result.get("patch_px"),
                "resolution_m":  result.get("resolution_m"),
                "ground_m":      result.get("tile_ground_m", result.get("ground_m")),
                "selected_orbit": result.get("selected_orbit"),
                "s2_bands":      result.get("s2_bands"),
                "s1_bands":      result.get("s1_bands"),
            }
            _write_json_artifact(pair_id, ACQUISITION_FILENAME, acquisition_metadata)

            update_progress("Writing metadata and finalizing...")

            # Refresh the pair object (GEE calls took time).
            pair = db.get(AOIImagePair, pair_id)
            if not pair:
                _result["error"] = "Image pair record disappeared during acquisition"
                return

            t1_window = result.get("t1_window")
            t2_window = result.get("t2_window")

            if t1_window and len(t1_window) == 2:
                pair.t1_start = t1_window[0]
                pair.t1_end   = t1_window[1]

            if t2_window and len(t2_window) == 2:
                pair.t2_start = t2_window[0]
                pair.t2_end   = t2_window[1]

            if result.get("patch_px") is not None:
                pair.patch_px = int(result["patch_px"])

            if result.get("resolution_m") is not None:
                pair.resolution_m = int(result["resolution_m"])

            ground_m = result.get("tile_ground_m", result.get("ground_m", 1280.0))
            if ground_m is not None:
                pair.ground_m = float(ground_m)

            if result.get("nx") is not None:
                pair.nx = int(result["nx"])

            fetched_at = datetime.now(timezone.utc)

            rows_updated = db.query(AOIImagePair).filter(
                AOIImagePair.id == pair_id,
                AOIImagePair.status == "fetching"
            ).update({
                "t1_start": pair.t1_start,
                "t1_end": pair.t1_end,
                "t2_start": pair.t2_start,
                "t2_end": pair.t2_end,
                "patch_px": pair.patch_px,
                "resolution_m": pair.resolution_m,
                "ground_m": pair.ground_m,
                "nx": pair.nx,
                "status": "done",
                "error_message": None,
                "fetched_at": fetched_at
            })

            if rows_updated == 0:
                db.rollback()
                return

            db.commit()

            _write_progress(
                pair_id,
                "Satellite acquisition completed.",
                state="done",
            )

            _result["ok"] = True

        except Exception as exc:
            db.rollback()
            _result["error"] = str(exc)

        finally:
            db.close()

    # ------------------------------------------------------------------
    # Run acquisition with an adaptive tile-aware timeout
    # ------------------------------------------------------------------
    t = _threading.Thread(target=_run_acquisition, daemon=True, name=f"geowatch-inner-{pair_id}")
    t.start()
    t.join(timeout=timeout_secs)

    if t.is_alive():
        # Timeout fired — signal inner thread to stop writing progress,
        # then atomically mark the pair as error.
        timeout_event.set()
        _mark_pair_error(
            pair_id,
            f"Satellite acquisition timed out after {timeout_secs // 60} minutes "
            f"(tile count={nx}).",
        )
        return

    if "error" in _result:
        _mark_pair_error(pair_id, _result["error"])




