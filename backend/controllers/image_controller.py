def trigger_fetch(aoi_id: str):
    """
    POST /api/aoi/<id>/fetch-images

    Starts the GEE acquisition for the requested AOI.

    Guards:
    1. Duplicate-fetch prevention — if a pair is already fetching, return it.
    2. Stale-fetch recovery — pairs stuck in 'fetching' for > _STALE_FETCH_MINUTES
       are automatically reset to 'error' so the user can retry.
    """

    db = SessionLocal()

    try:
        # ------------------------------------------------------------------
        # Load AOI
        # ------------------------------------------------------------------

        aoi = db.get(AOI, aoi_id)

        if not aoi:
            return jsonify({"error": "AOI not found"}), 404

        # ------------------------------------------------------------------
        # AOI settings
        # ------------------------------------------------------------------

        settings = aoi.settings or {}
        request_data = request.get_json(silent=True) or {}

        before_date = (
            settings.get("before_date")
            or request_data.get("before_date")
            or "K30_T1 (2020)"
        )
        after_date = (
            settings.get("after_date")
            or request_data.get("after_date")
            or "K30_T2 (2024)"
        )

        cover_area = _normalise_cover_area(settings)
        nx = int(cover_area[:-1])

        # ------------------------------------------------------------------
        # AOI coordinates
        # ------------------------------------------------------------------

        coordinates = aoi.coordinates

        if not coordinates:
            return jsonify({"error": "AOI has no coordinates"}), 400

        first_coordinate = coordinates[0]

        if not isinstance(first_coordinate, (list, tuple)):
            return jsonify({"error": "AOI coordinates are invalid"}), 400

        if len(first_coordinate) != 2:
            return jsonify({"error": "AOI coordinate must contain [lat, lon]"}), 400

        lat = float(first_coordinate[0])
        lon = float(first_coordinate[1])


        # ------------------------------------------------------------------
        # GUARD 2 — Duplicate-fetch prevention
        # If the AOI already has a pair in 'fetching', return it rather than
        # spawning a second competing GEE worker.
        # GUARD 3 — Stale-fetch recovery
        # If a pair in 'fetching' has had no progress heartbeat for
        # > _STALE_HEARTBEAT_MINUTES minutes, reset it to 'error' so the
        # user can retry cleanly.
        # ------------------------------------------------------------------

        existing_pairs = aoi.image_pairs or []
        for ep in existing_pairs:
            if ep.status == "fetching":
                # Check how long ago the progress file was last updated.
                # A running acquisition writes progress.json every few seconds.
                stale = False
                try:
                    from datetime import timedelta
                    progress_path = os.path.join(_pair_data_dir(str(ep.id)), "progress.json")
                    if os.path.isfile(progress_path):
                        mtime = os.path.getmtime(progress_path)
                        import time as _time
                        heartbeat_age_minutes = (_time.time() - mtime) / 60.0
                        if heartbeat_age_minutes > _STALE_HEARTBEAT_MINUTES:
                            stale = True
                    else:
                        # No progress file yet — fall back to creation time
                        if ep.created_at:
                            age = datetime.now(timezone.utc) - ep.created_at.replace(tzinfo=timezone.utc)
                            if age > timedelta(minutes=_STALE_HEARTBEAT_MINUTES):
                                stale = True
                except Exception:
                    pass

                if stale:
                    # Reset stale pair to error so a fresh fetch can proceed.
                    ep.status = "error"
                    ep.error_message = (
                        f"Acquisition lost progress heartbeat for more than "
                        f"{_STALE_HEARTBEAT_MINUTES} minutes and was automatically "
                        f"marked as failed. Please retry."
                    )
                    db.commit()
                    _write_progress(
                        str(ep.id),
                        ep.error_message,
                        state="error",
                    )
                    break  # allow a new pair to be created below

                else:
                    # Active fetch in progress — return existing pair
                    return jsonify({
                        "message": "Acquisition already in progress for this AOI.",
                        "pair": ep.to_dict(),
                    }), 202

        # ------------------------------------------------------------------
        # Create image-pair record
        # ------------------------------------------------------------------

        pair = AOIImagePair(
            aoi_id=aoi_id,
            before_date=before_date,
            after_date=after_date,
            nx=nx,
            patch_px=128,
            resolution_m=10,
            ground_m=1280.0,
            status="pending",
            error_message=None,
        )

        db.add(pair)
        db.commit()
        db.refresh(pair)

        pair_id = pair.id
        pair_dict = pair.to_dict()
        aoi_payload = _build_aoi_payload(aoi)

    except Exception as exc:
        db.rollback()
        return jsonify({"error": str(exc)}), 500

    finally:
        db.close()

    # ----------------------------------------------------------------------
    # Background worker
    # ----------------------------------------------------------------------

    worker = threading.Thread(
        target=_do_fetch,
        kwargs={
            "pair_id": pair_id,
            "lat": lat,
            "lon": lon,
            "before_date": before_date,
            "after_date": after_date,
            "cover_area": cover_area,
            "aoi_payload": aoi_payload,
        },
        daemon=True,
        name=f"geowatch-fetch-{pair_id}",
    )

    worker.start()

    return jsonify({
        "message": "Image fetch started",
        "pair": pair_dict,
    }), 202



